message("\n=== Downloading EIA-861 zip files ===")
download_eia_861(full_year_range, dir_eia_861)

message("\n=== Parsing EIA-861 long form (Sales_Ult_Cust) ===")
eia_long <- map_dfr(full_year_range, function(yr) {
  zip_file <- file.path(dir_eia_861, sprintf("f861%d.zip", yr))
  if (!file.exists(zip_file)) return(tibble())
  out <- tryCatch(
    parse_eia_861_long(zip_file, yr, state_abb),
    error = function(e) {
      warning(sprintf("Long-form parse failed for %d: %s", yr, e$message))
      tibble()
    }
  )
  if (nrow(out) > 0) {
    message(sprintf("  %d: %d %s utilities (long form)", yr, nrow(out), state_abb))
  }
  out
})

message("\n=== Parsing EIA-861 short form ===")
eia_short <- map_dfr(full_year_range, function(yr) {
  zip_file <- file.path(dir_eia_861, sprintf("f861%d.zip", yr))
  if (!file.exists(zip_file)) return(tibble())
  out <- tryCatch(
    parse_eia_861_short(zip_file, yr, state_abb),
    error = function(e) {
      warning(sprintf("Short-form parse failed for %d: %s", yr, e$message))
      tibble()
    }
  )
  if (nrow(out) > 0) {
    message(sprintf("  %d: %d %s utilities (short form)", yr, nrow(out), state_abb))
  }
  out
})

# Combine long + short, keeping long form when a utility reported both
eia_all_wi <- bind_rows(eia_long, eia_short) %>%
  arrange(utility_name, emissions_year, desc(data_source == "eia_861_long")) %>%
  group_by(utility_name, emissions_year) %>%
  slice(1) %>%
  ungroup()

# Restrict to in-scope WI utilities
wi_utility_elec_activity_eia861 <- eia_all_wi %>%
  filter(utility_name %in% wi_elec_utils_scope$utility_name) %>%
  left_join(
    wi_elec_utils_scope %>%
      distinct(utility_name, utility_type),
    by = "utility_name"
  ) %>%
  select(
    utility_name, utility_name_raw, utility_type, state, emissions_year,
    any_of(c(
      "residential", "commercial", "industrial", "transportation", "total",
      "residential_customers", "commercial_customers",
      "industrial_customers", "transportation_customers", "total_customers"
    )),
    unit_activity, data_source, eia_form
  ) %>%
  arrange(utility_name, emissions_year)

