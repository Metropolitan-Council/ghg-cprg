# 02_compile_eia_wi_elec_activity.R
# ──────────────────────────────────────────────────────────────────────────────
# Compile a utility x year electricity activity table for WI in-scope utilities
# by downloading and parsing EIA-861 detail files across 2005–latest.
#
# Wisconsin electric cooperatives and municipals do not report to the state in
# the same way MN utilities do (via 7610). County-level deliveries are not
# published for  WI utilities, so EIA-861 is used as the base activity
# source. Downstream scripts allocate these utility x state totals to counties
# using customer-count / population weights.
#
# Inputs:
#   distinct_electricity_util_type_WI.RDS  — WI in-scope utility list
#   EIA-861 annual zip files               — downloaded from eia.gov
#     Sales_Ult_Cust  (long form: sector MWh, customer counts, revenues)
#     Short_Form      (short form: total MWh + customers only)
#
# Outputs:
#   WI_utility_elec_activity_eia861.RDS
#       utility_name, utility_name_raw, state, emissions_year,
#       residential, commercial, industrial, transportation, total,
#       residential_customers, commercial_customers, industrial_customers,
#       transportation_customers, total_customers,
#       unit_activity, data_source, eia_form
#
# data_source values:
#   "eia_861_long"   — from Sales_Ult_Cust (long form)
#   "eia_861_short"  — from Short_Form (short form; small utilities/coops)
# ──────────────────────────────────────────────────────────────────────────────

