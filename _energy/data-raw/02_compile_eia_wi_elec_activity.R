harmonize_eia_names_wi <- function(names) {
  # Case- and whitespace-insensitive match: EIA-861 raw names for the same
  # utility vary in capitalization across years (older "reformatted" 2005-2011
  # archives in particular are often ALL CAPS), so an exact-match lookup
  # silently misses years even when the name is otherwise a known variant.
  normalized <- toupper(trimws(names))
  lookup_keys <- toupper(trimws(names(eia_name_lookup_wi)))
  idx <- match(normalized, lookup_keys)
  ifelse(is.na(idx), names, unname(eia_name_lookup_wi[idx]))
}

# --- download EIA-861 zip files ----------------------------------------------

download_eia_861 <- function(years, dest_dir) {
  for (yr in years) {
    zip_file <- file.path(dest_dir, sprintf("f861%d.zip", yr))
    if (file.exists(zip_file)) next

    # URL pattern varies by year:
    #   latest       : .../eia861/zip/f861YYYY.zip
    #   2012-latest-1: .../eia861/archive/zip/f861YYYY.zip
    #   2005-2011    : .../eia861/archive/zip/861_YYYY.zip (reformatted)
    urls <- if (yr >= 2012) {
      c(
        sprintf("https://www.eia.gov/electricity/data/eia861/zip/f861%d.zip", yr),
        sprintf("https://www.eia.gov/electricity/data/eia861/archive/zip/f861%d.zip", yr)
      )
    } else {
      c(
        sprintf("https://www.eia.gov/electricity/data/eia861/archive/zip/861_%d.zip", yr),
        sprintf("https://www.eia.gov/electricity/data/eia861/archive/zip/f861%d.zip", yr)
      )
    }

    downloaded <- FALSE
    for (url in urls) {
      res <- tryCatch(
        {
          download.file(url, zip_file, mode = "wb", quiet = TRUE)
          TRUE
        },
        error = function(e) FALSE,
        warning = function(w) FALSE
      )
      if (isTRUE(res) && file.exists(zip_file) && file.info(zip_file)$size > 1024) {
        message(sprintf("  downloaded EIA-861 %d", yr))
        downloaded <- TRUE
        break
      } else if (file.exists(zip_file)) {
        file.remove(zip_file)
      }
    }
    if (!downloaded) warning(sprintf("Failed to download EIA-861 for %d", yr))
  }
}

# --- helpers to find and read files inside a zip -----------------------------

find_file_in_zip <- function(zip_file, patterns) {
  zip_contents <- unzip(zip_file, list = TRUE)$Name
  for (p in patterns) {
    hits <- grep(p, zip_contents, value = TRUE, ignore.case = TRUE)
    if (length(hits) > 0) {
      # prefer xlsx over xls over csv
      hits <- hits[order(!grepl("\\.xlsx$", hits, ignore.case = TRUE),
        !grepl("\\.xls$", hits, ignore.case = TRUE))]
      return(hits[1])
    }
  }
  NA_character_
}

read_eia_tabular <- function(zip_file, file_in_zip) {
  temp_dir <- tempdir()
  unzip(zip_file, files = file_in_zip, exdir = temp_dir, overwrite = TRUE)
  path <- file.path(temp_dir, file_in_zip)

  # Detect header row by scanning for a row that contains "Utility" and "State"
  detect_header_and_read <- function(reader_preview, reader_full) {
    preview <- tryCatch(reader_preview(), error = function(e) NULL)
    if (is.null(preview)) return(NULL)
    header_row <- NA_integer_
    for (r in seq_len(nrow(preview))) {
      row_vals <- toupper(as.character(unlist(preview[r, ])))
      if (any(grepl("UTILITY", row_vals)) && any(grepl("STATE", row_vals))) {
        header_row <- r
        break
      }
    }
    skip_n <- if (!is.na(header_row)) header_row - 1 else 0
    tryCatch(reader_full(skip_n), error = function(e) NULL)
  }

  if (grepl("\\.xlsx$|\\.xls$", file_in_zip, ignore.case = TRUE)) {
    raw <- detect_header_and_read(
      reader_preview = function() readxl::read_excel(path, col_names = FALSE, n_max = 10),
      reader_full = function(skip_n) readxl::read_excel(path, skip = skip_n, guess_max = 10000)
    )
  } else {
    raw <- detect_header_and_read(
      reader_preview = function() readr::read_csv(path, col_names = FALSE, n_max = 10, show_col_types = FALSE),
      reader_full = function(skip_n) readr::read_csv(path, skip = skip_n, show_col_types = FALSE, guess_max = 10000)
    )
  }

  if (is.null(raw) || nrow(raw) == 0) return(NULL)

  # Standardize column names
  names(raw) <- tolower(trimws(names(raw)))
  names(raw) <- gsub("[\\s._]+", "_", names(raw))
  names(raw) <- gsub("_+$", "", names(raw))
  raw
}

find_col <- function(col_names, patterns) {
  for (p in patterns) {
    hits <- grep(p, col_names, value = TRUE, ignore.case = TRUE)
    if (length(hits) > 0) return(hits[1])
  }
  NA_character_
}

safe_numeric <- function(x) suppressWarnings(as.numeric(as.character(x)))

# --- parse Sales to Ultimate Customers (long form) ---------------------------
# Long form provides sector MWh (residential/commercial/industrial/transport)
# and customer counts by sector.

parse_eia_861_long <- function(zip_file, year, state_abb) {
  file_in_zip <- find_file_in_zip(
    zip_file,
    patterns = c("sales_ult_cust", "sales_ult", "sales_to_ultimate")
  )
  if (is.na(file_in_zip)) return(tibble())

  raw <- read_eia_tabular(zip_file, file_in_zip)
  if (is.null(raw)) return(tibble())

  col_names <- names(raw)
  name_col <- find_col(col_names, c("^utility_name$", "utility.*name", "^utility$"))
  state_col <- find_col(col_names, c("^state$", "^_tate$", "tate$", "^st$"))
  if (is.na(name_col) || is.na(state_col)) return(tibble())

  # Sector MWh: positional if not clearly named. EIA convention across years:
  # residential, commercial, industrial, transportation, total (in that order)
  mwh_cols <- grep("megawatthour|megawatt.*hour|mwh|sales_.*mwh", col_names,
    value = TRUE, ignore.case = TRUE)
  cust_cols <- grep("^customer|customers?$|count", col_names,
    value = TRUE, ignore.case = TRUE)
  # narrow customers columns: EIA convention is res/com/ind/transp/total after
  # the sector MWh + revenue blocks. We'll just take the last 5 "customer" cols.
  cust_cols_positional <- tail(cust_cols, 5)

  res_col <- find_col(col_names, c("^residential$", "res.*megawatt", "res.*mwh"))
  com_col <- find_col(col_names, c("^commercial$", "comm.*megawatt", "com.*mwh"))
  ind_col <- find_col(col_names, c("^industrial$", "ind.*megawatt", "ind.*mwh"))
  trn_col <- find_col(col_names, c("^transportation$", "trans.*megawatt", "trans.*mwh"))
  tot_col <- find_col(col_names, c("^total$", "total.*megawatt", "total.*mwh"))

  if (is.na(res_col) && length(mwh_cols) >= 5) {
    res_col <- mwh_cols[1]; com_col <- mwh_cols[2]
    ind_col <- mwh_cols[3]; trn_col <- mwh_cols[4]
    tot_col <- mwh_cols[5]
  } else if (is.na(res_col) && length(mwh_cols) >= 4) {
    res_col <- mwh_cols[1]; com_col <- mwh_cols[2]
    ind_col <- mwh_cols[3]; tot_col <- mwh_cols[4]
  }

  # Filter to state
  state_hits <- which(toupper(as.character(raw[[state_col]])) == toupper(state_abb))
  if (length(state_hits) == 0) return(tibble())
  raw_st <- raw[state_hits, ]

  result <- tibble(
    utility_name_raw = as.character(raw_st[[name_col]]),
    state            = state_abb,
    emissions_year   = as.integer(year)
  )
  if (!is.na(res_col)) result$residential    <- safe_numeric(raw_st[[res_col]])
  if (!is.na(com_col)) result$commercial     <- safe_numeric(raw_st[[com_col]])
  if (!is.na(ind_col)) result$industrial     <- safe_numeric(raw_st[[ind_col]])
  if (!is.na(trn_col)) result$transportation <- safe_numeric(raw_st[[trn_col]])
  if (!is.na(tot_col)) result$total          <- safe_numeric(raw_st[[tot_col]])

  # Customer counts (positional fallback)
  if (length(cust_cols_positional) >= 5) {
    result$residential_customers    <- safe_numeric(raw_st[[cust_cols_positional[1]]])
    result$commercial_customers     <- safe_numeric(raw_st[[cust_cols_positional[2]]])
    result$industrial_customers     <- safe_numeric(raw_st[[cust_cols_positional[3]]])
    result$transportation_customers <- safe_numeric(raw_st[[cust_cols_positional[4]]])
    result$total_customers          <- safe_numeric(raw_st[[cust_cols_positional[5]]])
  } else if (length(cust_cols_positional) >= 4) {
    result$residential_customers <- safe_numeric(raw_st[[cust_cols_positional[1]]])
    result$commercial_customers  <- safe_numeric(raw_st[[cust_cols_positional[2]]])
    result$industrial_customers  <- safe_numeric(raw_st[[cust_cols_positional[3]]])
    result$total_customers       <- safe_numeric(raw_st[[cust_cols_positional[4]]])
  }

  # Compute total if missing but sectors are present
  sector_cols <- intersect(c("residential", "commercial", "industrial", "transportation"), names(result))
  if (!"total" %in% names(result) && length(sector_cols) >= 3) {
    result$total <- rowSums(result[, sector_cols], na.rm = TRUE)
  }

  result %>%
    mutate(
      utility_name  = harmonize_eia_names_wi(utility_name_raw),
      unit_activity = "MWh",
      data_source   = "eia_861_long",
      eia_form      = "EIA-861"
    ) %>%
    filter(!is.na(total), total > 0)
}

# --- parse Short Form (small utility survey; total only) ---------------------

parse_eia_861_short <- function(zip_file, year, state_abb) {
  file_in_zip <- find_file_in_zip(
    zip_file,
    patterns = c("short_form", "shortform", "^short", "^861s")
  )
  if (is.na(file_in_zip)) return(tibble())

  raw <- read_eia_tabular(zip_file, file_in_zip)
  if (is.null(raw)) return(tibble())

  col_names <- names(raw)
  name_col <- find_col(col_names, c("^utility_name$", "utility.*name", "^utility$"))
  state_col <- find_col(col_names, c("^state$", "^_tate$", "tate$", "^st$"))
  if (is.na(name_col) || is.na(state_col)) return(tibble())

  # Short form typically reports one MWh total + one customer total
  mwh_col <- find_col(col_names, c(
    "sales.*mwh", "megawatthour", "total.*mwh", "sold.*mwh", "^mwh$"
  ))
  cust_col <- find_col(col_names, c(
    "total.*customer", "customer.*total", "^customers?$", "^customer_count$"
  ))

  state_hits <- which(toupper(as.character(raw[[state_col]])) == toupper(state_abb))
  if (length(state_hits) == 0) return(tibble())
  raw_st <- raw[state_hits, ]

  result <- tibble(
    utility_name_raw = as.character(raw_st[[name_col]]),
    state            = state_abb,
    emissions_year   = as.integer(year),
    total            = if (!is.na(mwh_col)) safe_numeric(raw_st[[mwh_col]]) else NA_real_,
    total_customers  = if (!is.na(cust_col)) safe_numeric(raw_st[[cust_col]]) else NA_real_
  ) %>%
    mutate(
      utility_name  = harmonize_eia_names_wi(utility_name_raw),
      unit_activity = "MWh",
      data_source   = "eia_861_short",
      eia_form      = "EIA-861S"
    ) %>%
    filter(!is.na(total), total > 0)

  result
}

